"""Any to any: projects saved by Bambu Studio, OrcaSlicer or a maker's fork, and SlicerBridge's own files, go in."""
import zipfile
from pathlib import Path

import pytest

from builders import bambu_project
from slicerbridge.checks import u1 as check
from slicerbridge.cli import _default_name, main


@pytest.mark.parametrize("application, client_version", [
    ("BambuStudio-02.08.02.61", "02.08.02.61"),   # Bambu Studio
    ("BambuStudio-02.06.00.51", "02.06.00.51"),   # OrcaSlicer 2.4.2 stamps itself so
    ("QIDIStudio-02.07.02.73", None),             # QIDI Studio: its own stamp, no client version
    ("BambuStudio-2.0.0.3", None),                # Anycubic Slicer Next
    ("ElegooSlicer-1.5.3.5", "01.05.03.05"),      # ElegooSlicer
])
def test_projects_from_any_of_these_slicers(tmp_path, application, client_version):
    src = bambu_project(tmp_path / "in.3mf", application=application, client_version=client_version)
    assert main(["convert", str(src), "--name", "Cube", "-p", "u1", "-o", str(tmp_path / "out")]) == 0
    f = tmp_path / "out" / "Cube" / "Cube - Snapmaker U1.3mf"
    assert check.audit(f, src)[1] == []
    with zipfile.ZipFile(f) as z:  # the U1 template's version, even when the source had none
        assert check.stamp(z) == check.stamp(zipfile.ZipFile(check.DATA / "u1_template.3mf"))


def test_a_slicerbridge_file_goes_back_in(project, tmp_path):
    assert main(["convert", str(project), "--name", "Cube", "-p", "u1", "-o", str(tmp_path / "a")]) == 0
    first = tmp_path / "a" / "Cube" / "Cube - Snapmaker U1.3mf"
    assert main(["convert", str(first), "-p", "u1", "-o", str(tmp_path / "b")]) == 0
    again = tmp_path / "b" / "Cube" / "Cube - Snapmaker U1.3mf"  # named "Cube", not "Cube - Snapmaker U1"
    assert check.audit(again, first)[1] == []


def test_default_name_drops_the_printer():
    assert _default_name(Path("Cube - QIDI Q2.3mf")) == "Cube"
    assert _default_name(Path("Shop - Cube - Anycubic Kobra 3 Max.3mf")) == "Shop - Cube"
    assert _default_name(Path("Cube - Prusa MMU3 - Plate 2.3mf")) == "Cube"
    assert _default_name(Path("My Dragon.3mf")) == "My Dragon"


def test_a_prusaslicer_project_is_named_as_such(tmp_path):
    f = tmp_path / "prusa.3mf"
    with zipfile.ZipFile(f, "w") as z:
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/Slic3r_PE.config", "; generated by PrusaSlicer")
    with pytest.raises(SystemExit, match="is a PrusaSlicer project"):
        main(["inspect", str(f)])


def test_a_mesh_only_3mf_is_refused_clearly(tmp_path):
    f = tmp_path / "mesh.3mf"
    with zipfile.ZipFile(f, "w") as z:
        z.writestr("3D/3dmodel.model", "<model/>")
    with pytest.raises(SystemExit, match="carries no slicer project"):
        main(["convert", str(f), "-p", "u1"])
